// Format function for strings with placeholders like {name} or {count}
export function formatString(
  template: string,
  params: Record<string, string | number>
): string {
  return template.replace(
    /\{(\w+)\}/g,
    (_, key) => String(params[key] ?? `{${key}}`)
  );
}